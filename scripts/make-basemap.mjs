#!/usr/bin/env node
// Makes src/content/basemap.ts, the coverage map's background (plan P3,
// decision 17): US and Canadian states and provinces from Natural Earth 1:50m
// admin-1 (public domain), simplified and projected once, so the page needs no
// tiles and no third party. A developer's tool: not part of the build.
//   curl -fsSL -o /tmp/ne.geojson https://raw.githubusercontent.com/nvkelso/natural-earth-vector/ca96624a56bd078437bca8184e78163e5039ad19/geojson/ne_50m_admin_1_states_provinces.geojson
//   node scripts/make-basemap.mjs /tmp/ne.geojson
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const SOURCE_SHA256 = '69a0e06e640b2d505858ae1cb63034e4677f3000b35a98e16312932b98c426b9';
const OUT = 'src/content/basemap.ts';
const MAX_BYTES = 300 * 1024;
const TOLERANCE_DEG = 0.03;
// Must match project() in src/lib/map-projection.ts.
const LON_SCALE = Math.cos((40 * Math.PI) / 180);
const project = (lat, lon) => [(lon + 170) * LON_SCALE * 10, (72 - lat) * 10];

const file = process.argv[2];
if (!file) {
  console.error('usage: node scripts/make-basemap.mjs SRC.geojson');
  process.exit(2);
}
const raw = readFileSync(file);
const got = createHash('sha256').update(raw).digest('hex');
if (got !== SOURCE_SHA256) {
  console.error(`${file}: SHA-256 ${got}, not the pinned ${SOURCE_SHA256}`);
  process.exit(1);
}

/** Douglas-Peucker in degrees, the ring's ends kept; iterative, so a long coast can't overflow the stack. */
function simplify(points, tolerance) {
  if (points.length < 3) return points;
  const keep = new Array(points.length).fill(false);
  keep[0] = keep[points.length - 1] = true;
  const stack = [[0, points.length - 1]];
  while (stack.length > 0) {
    const [a, b] = stack.pop();
    const [ax, ay] = points[a];
    const [bx, by] = points[b];
    const dx = bx - ax;
    const dy = by - ay;
    const len = Math.hypot(dx, dy);
    let far = -1;
    let dist = tolerance;
    for (let i = a + 1; i < b; i++) {
      const [px, py] = points[i];
      const d = len === 0 ? Math.hypot(px - ax, py - ay) : Math.abs(dy * (px - ax) - dx * (py - ay)) / len;
      if (d > dist) {
        far = i;
        dist = d;
      }
    }
    if (far >= 0) {
      keep[far] = true;
      stack.push([a, far], [far, b]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

const num = (x) => {
  const s = x.toFixed(1);
  return s.endsWith('.0') ? s.slice(0, -2) : s;
};

function ringPath(ring) {
  // A closed ring: split it in two, so the two ends of the line aren't the same point.
  const half = Math.floor(ring.length / 2);
  const simple = [...simplify(ring.slice(0, half + 1), TOLERANCE_DEG), ...simplify(ring.slice(half), TOLERANCE_DEG).slice(1)];
  if (simple.length < 4) return '';
  let d = '';
  let last = '';
  for (const [lon, lat] of simple) {
    const [x, y] = project(lat, lon);
    const pt = `${num(x)} ${num(y)}`;
    if (pt === last) continue;
    d += d === '' ? `M${pt}` : `L${pt}`;
    last = pt;
  }
  return `${d}Z`;
}

const geo = JSON.parse(raw.toString());
const regions = [];
for (const f of geo.features) {
  const p = f.properties;
  if (p.iso_a2 !== 'US' && p.iso_a2 !== 'CA') continue;
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  // Past the antimeridian (the far Aleutians): off this projection, and no land anyone serves.
  const d = polys
    .filter((poly) => poly[0].every(([lon]) => lon < 0))
    .map((poly) => ringPath(poly[0]))
    .join('');
  if (d) regions.push({ code: `${p.iso_a2}-${String(p.postal ?? p.iso_3166_2 ?? p.name).replace(/^.*-/, '')}`, d });
}
regions.sort((a, b) => (a.code < b.code ? -1 : 1));
const body = `// Generated by scripts/make-basemap.mjs from Natural Earth 1:50m admin-1 (public domain), SHA-256 ${SOURCE_SHA256}. Do not edit.

export const BASEMAP: { lonScale: number; regions: { code: string; d: string }[] } = ${JSON.stringify({ lonScale: Number(LON_SCALE.toFixed(6)), regions })};
`;
if (Buffer.byteLength(body) > MAX_BYTES) {
  console.error(`${OUT} would be ${Buffer.byteLength(body)} bytes, over ${MAX_BYTES}`);
  process.exit(1);
}
writeFileSync(OUT, body);
console.log(`${OUT}: ${regions.length} regions, ${Buffer.byteLength(body)} bytes`);
